const normalizeReadingSlug = (slug) => (typeof slug === 'string' ? slug.trim() : '')

const normalizeReadingText = (value) => (typeof value === 'string' ? value.trim() : '')

const cloneHighlightList = (items) => {
  if (!Array.isArray(items)) {
    return []
  }

  return items.map((item) => ({ ...item }))
}

const cloneReadingBookRecord = (book) => {
  if (!book || typeof book !== 'object') {
    return null
  }

  const normalizedSlug = normalizeReadingSlug(book.slug)
  if (!normalizedSlug) {
    return null
  }

  return {
    ...book,
    slug: normalizedSlug,
    note: normalizeReadingText(book.note),
    intro: normalizeReadingText(book.intro),
    review: normalizeReadingText(book.review),
    tags: Array.isArray(book.tags) ? [...book.tags] : [],
    meta: book.meta && typeof book.meta === 'object' ? { ...book.meta } : undefined,
    progress: book.progress && typeof book.progress === 'object' ? { ...book.progress } : undefined,
    highlights: cloneHighlightList(book.highlights)
  }
}

